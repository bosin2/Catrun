"""Stage3-only calibrated parent duplicates and per-component Material Instances.

ROOT WRITER SLOT ONLY. Run main() from the current Stage3 editor or a coordinated
headless editor. Inputs are generated by Materials/probe.py and calibrate.py.
Never changes original materials/textures/meshes or any map geometry/gameplay.
"""
import hashlib
import json
from pathlib import Path
import unreal as u

ROOT = Path(u.Paths.project_dir()).resolve()
OUT = ROOT / 'Saved/Stage3MaterialCorrection20261125/Materials'
DEST = '/Game/Environment/Stage3/ColorCorrection_20261125'
OWNER = 'Stage3MaterialCorrection20261125_v1'
EA = u.EditorAssetLibrary
ML = u.MaterialEditingLibrary
AT = u.AssetToolsHelpers.get_asset_tools()
PROPERTIES = ['NORMAL', 'AMBIENT_OCCLUSION', 'ROUGHNESS', 'METALLIC', 'OPACITY_MASK', 'OPACITY', 'EMISSIVE_COLOR', 'WORLD_POSITION_OFFSET']


def objpath(obj): return obj.get_path_name() if obj else None


def graph_signature(material):
    """Stable comparison of preserved graph outputs and original expression links."""
    result = {'properties':{}, 'nodes':{}, 'settings':{}}
    for name in PROPERTIES:
        prop = getattr(u.MaterialProperty,'MP_'+name)
        node = ML.get_material_property_input_node(material,prop)
        result['properties'][name] = [node.get_name() if node else None,
            ML.get_material_property_input_node_output_name(material,prop) if node else None]
    for node in ML.get_material_expressions(material):
        row = {'class':node.get_class().get_name(),
               'inputs':[x.get_name() if x else None for x in ML.get_inputs_for_material_expression(material,node)]}
        for attr in ('texture','material_function','parameter_name','code','sampler_type','const_coordinate','coordinates','const_a','const_b'):
            try:
                value=node.get_editor_property(attr)
                row[attr]=objpath(value) if isinstance(value,u.Object) else str(value)
            except Exception: pass
        result['nodes'][node.get_name()] = row
    for name in ('blend_mode','two_sided','opacity_mask_clip_value','material_domain','shading_model','dithered_lod_transition'):
        try: result['settings'][name] = str(material.get_editor_property(name))
        except Exception: pass
    return result


def assert_preserved(source, duplicate):
    a,b=graph_signature(source),graph_signature(duplicate)
    assert a['settings']==b['settings'], 'Material render settings changed'
    assert a['properties']==b['properties'], 'Non-BaseColor output changed'
    for name,row in a['nodes'].items():
        assert b['nodes'][name]==row, ('Original expression changed',name)
    return {'settings':b['settings'],'preserved_outputs':b['properties'],'original_node_count':len(a['nodes']),
            'new_node_count':len(b['nodes'])}


def owned_load(path):
    if not EA.does_asset_exist(path): return None
    obj=EA.load_asset(path)
    assert EA.get_metadata_tag(obj,'Stage3ColorCorrectionOwner')==OWNER, ('Unowned destination',path)
    return obj


def parent_for(cal):
    source=EA.load_asset(cal['source_base_material']); assert isinstance(source,u.Material)
    suffix=hashlib.sha256(objpath(source).encode()).hexdigest()[:8]
    path=DEST+'/Parents/M_CC_'+source.get_name().removeprefix('M_')+'_'+suffix
    parent=owned_load(path)
    if parent:
        assert_preserved(source,parent)
        return parent
    parent=EA.duplicate_asset(objpath(source),path); assert parent
    EA.set_metadata_tag(parent,'Stage3ColorCorrectionOwner',OWNER)
    EA.set_metadata_tag(parent,'Stage3ColorCorrectionSource',objpath(source))
    base=ML.get_material_property_input_node(parent,u.MaterialProperty.MP_BASE_COLOR)
    output=ML.get_material_property_input_node_output_name(parent,u.MaterialProperty.MP_BASE_COLOR)
    assert isinstance(base,u.MaterialExpressionTextureSample) and output=='RGB'
    assert objpath(base.texture)==cal['source_texture']
    norm=ML.create_material_expression(parent,u.MaterialExpressionConstant3Vector,-350,-500)
    norm.set_editor_property('constant',u.LinearColor(*cal['source_normalization'],1))
    norm.set_editor_property('desc','Fixed inverse mean of linear source BaseColor texels; preserves original texture variation')
    normalize=ML.create_material_expression(parent,u.MaterialExpressionMultiply,-100,-350)
    assert ML.connect_material_expressions(base,output,normalize,'A')
    assert ML.connect_material_expressions(norm,'',normalize,'B')
    tint=ML.create_material_expression(parent,u.MaterialExpressionVectorParameter,-100,-650)
    tint.set_editor_property('parameter_name','ColorTint')
    tint.set_editor_property('default_value',u.LinearColor(*cal['source_mean_linear'],1))
    tint.set_editor_property('group','Stage3 Color Correction')
    tint.set_editor_property('desc','Desired representative BaseColor, linear RGB. Enable sRGB in color picker for byte targets.')
    tinted=ML.create_material_expression(parent,u.MaterialExpressionMultiply,150,-350)
    assert ML.connect_material_expressions(normalize,'',tinted,'A')
    assert ML.connect_material_expressions(tint,'RGB',tinted,'B')
    brightness=ML.create_material_expression(parent,u.MaterialExpressionScalarParameter,150,-650)
    brightness.set_editor_property('parameter_name','Brightness')
    brightness.set_editor_property('default_value',1.)
    brightness.set_editor_property('slider_min',0.)
    brightness.set_editor_property('slider_max',2.)
    brightness.set_editor_property('group','Stage3 Color Correction')
    final=ML.create_material_expression(parent,u.MaterialExpressionMultiply,400,-350)
    assert ML.connect_material_expressions(tinted,'',final,'A')
    assert ML.connect_material_expressions(brightness,'',final,'B')
    assert ML.connect_material_property(final,'',u.MaterialProperty.MP_BASE_COLOR)
    assert_preserved(source,parent)
    ML.recompile_material(parent)
    assert EA.save_loaded_asset(parent)
    return parent


def instance_for(source,parent,cal):
    key=objpath(source)+'|'+cal['role']
    suffix=hashlib.sha256(key.encode()).hexdigest()[:8]
    name='MI_CC_'+cal['role']+'_'+source.get_name().removeprefix('M_').removeprefix('MI_')+'_'+suffix
    path=DEST+'/Instances/'+name
    instance=owned_load(path)
    if not instance:
        if isinstance(source,u.MaterialInstanceConstant):
            # Preserve existing instance overrides, including device-readability state.
            instance=EA.duplicate_asset(objpath(source),path)
        else:
            instance=AT.create_asset(name,DEST+'/Instances',u.MaterialInstanceConstant,u.MaterialInstanceConstantFactoryNew())
        assert instance
        EA.set_metadata_tag(instance,'Stage3ColorCorrectionOwner',OWNER)
    ML.set_material_instance_parent(instance,parent)
    # UE5.8 MaterialEditingLibrary.cpp initializes bResult=false and never changes
    # it in these setters (lines 1491/1573). Verify actual readback, not that flag.
    ML.set_material_instance_vector_parameter_value(instance,'ColorTint',u.LinearColor(*cal['color_tint'],1))
    ML.set_material_instance_scalar_parameter_value(instance,'Brightness',cal['brightness'])
    actual=ML.get_material_instance_vector_parameter_value(instance,'ColorTint')
    assert max(abs(a-b) for a,b in zip((actual.r,actual.g,actual.b),cal['color_tint']))<1e-6, ('ColorTint readback',objpath(instance),actual)
    assert abs(ML.get_material_instance_scalar_parameter_value(instance,'Brightness')-cal['brightness'])<1e-6
    EA.set_metadata_tag(instance,'Stage3ColorCorrectionSource',objpath(source))
    EA.set_metadata_tag(instance,'Stage3ColorCorrectionRole',cal['role'])
    ML.update_material_instance(instance)
    assert EA.save_loaded_asset(instance)
    return instance


def main(save_map=True):
    world=u.get_editor_subsystem(u.UnrealEditorSubsystem).get_editor_world()
    assert world.get_path_name()=='/Game/Maps/Stage3.Stage3', ('Load Stage3 explicitly before applying',world.get_path_name())
    data=json.loads((OUT/'calibration.json').read_text())
    # Source PNG drift invalidates calibration. Validate all source data up front.
    for texture,row in data['textures'].items():
        assert hashlib.sha256(Path(row['source']).read_bytes()).hexdigest()==row['sha256'], ('Texture drift',texture)
    actors={a.get_actor_label():a for a in u.get_editor_subsystem(u.EditorActorSubsystem).get_all_level_actors()}
    bindings=[]
    for row in data['assignments']:
        actor=actors[row['actor']]
        comps=[c for c in actor.get_components_by_class(u.MeshComponent) if c.get_name()==row['component']]
        assert len(comps)==1,(row['actor'],row['component'])
        comp=comps[0]
        mesh=comp.get_skinned_asset() if isinstance(comp,u.SkeletalMeshComponent) else comp.static_mesh
        assert objpath(mesh)==row['mesh']
        current=comp.get_material(row['slot'])
        assert objpath(current)==row['source_material'] or EA.get_metadata_tag(current,'Stage3ColorCorrectionSource')==row['source_material'], ('Slot drift',row,objpath(current))
        bindings.append((row,comp))
    report={'success':False,'formula':data['formula'],'metric':data['metric'],'parents':{},'instances':{},'assignments':[],
            'preserved_slots':data['preserved'],'role_counts':data['role_counts']}
    try:
        instances={}
        for row,comp in bindings:
            cal=data['calibrations'][row['calibration']]
            key=(row['source_material'],cal['role'])
            if key not in instances:
                parent=parent_for(cal)
                source=EA.load_asset(row['source_material']); assert source
                instance=instance_for(source,parent,cal)
                instances[key]=instance
                report['parents'][objpath(parent)]={'source':cal['source_base_material'],
                    'graph':assert_preserved(source.get_base_material(),parent)}
                report['instances'][objpath(instance)]={'source':objpath(source),'parent':objpath(parent),'calibration':row['calibration'],
                    'ColorTint':cal['color_tint'],'Brightness':cal['brightness'],'target_srgb':cal['target_srgb']}
            instance=instances[key]
            comp.set_material(row['slot'],instance)
            assert comp.get_material(row['slot'])==instance
            report['assignments'].append(dict(row,assigned_material=objpath(instance)))
        if save_map: assert u.get_editor_subsystem(u.LevelEditorSubsystem).save_current_level()
        report['success']=True
        report['map_saved']=save_map
    finally:
        OUT.mkdir(parents=True,exist_ok=True)
        (OUT/'application_report.json').write_text(json.dumps(report,indent=2),encoding='utf8')
    print('STAGE3_MATERIAL_CORRECTION_OK',len(report['parents']),len(report['instances']),len(report['assignments']))
    return report


if __name__=='__main__': main()
